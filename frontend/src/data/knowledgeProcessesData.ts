export function matchesProcessBlock(block: KnowledgeProcessBlock, needle: string): boolean {
  if (!needle) return true;
  const blob = `${block.title} ${block.searchBlob} ${block.paragraphs.join(' ')}`.toLowerCase();
  return blob.includes(needle);
}
